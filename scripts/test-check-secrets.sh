#!/usr/bin/env bash
# =============================================================================
# Fixture tests for check-secrets.sh's inline Compose credential guard.
# Each fixture copies the guard into a throwaway git repo with one Compose
# file and checks the exit code: inline --admin-password forms must fail (1),
# --admin-password-file must pass (0).
# =============================================================================
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FAILS=0

run_fixture() {
  local name="$1" expected="$2" body="$3" tmp rc
  tmp="$(mktemp -d)"
  mkdir -p "$tmp/scripts/lib" "$tmp/compose" "$tmp/secrets"
  cp "$HERE/check-secrets.sh" "$tmp/scripts/"
  cp "$HERE/lib/common.sh" "$tmp/scripts/lib/"
  printf 'services: {}\n' > "$tmp/docker-compose.yml"
  printf '%s\n' "$body" > "$tmp/compose/06-tools.yml"
  git -C "$tmp" init -q
  bash "$tmp/scripts/check-secrets.sh" >/dev/null 2>&1; rc=$?
  rm -rf "$tmp"
  if [[ "$rc" == "$expected" ]]; then
    printf 'ok   %s (exit %s)\n' "$name" "$rc"
  else
    printf 'FAIL %s: expected exit %s, got %s\n' "$name" "$expected" "$rc"
    (( FAILS++ )) || true
  fi
}

run_fixture "equals form" 1 '    command:
      - --admin-password=$$2y$$05$$abc'
run_fixture "space form" 1 '    command: --admin-password $$2y$$05$$abc'
run_fixture "separate list argument" 1 '    command:
      - --admin-password
      - $$2y$$05$$abc'
run_fixture "quoted list argument" 1 '    command: ["-H", "unix:///var/run/docker.sock", "--admin-password", "$$2y$$05$$abc"]'
run_fixture "password file is allowed" 0 '    command:
      - --admin-password-file=/run/secrets/portainer_admin_password'

# --- check-secret-files.sh: LAB_SECRETS_DIR parsing ------------------------
# Each .env form must resolve to ./secrets/local, where every file exists, so
# the check passes (0). A wrong parse points at a missing directory (exit 1).
run_env_fixture() {
  # run_env_fixture <name> <expected exit> <.env line> [omit-portainer]
  local name="$1" expected="$2" line="$3" omit="${4:-}" tmp rc f
  tmp="$(mktemp -d)"
  mkdir -p "$tmp/scripts/lib" "$tmp/secrets/local"
  cp "$HERE/check-secret-files.sh" "$tmp/scripts/"
  cp "$HERE/lib/common.sh" "$tmp/scripts/lib/"
  cp "$HERE/../docker-compose.yml" "$tmp/"
  for f in $(sed -n 's#^ *file: \${LAB_SECRETS_DIR:-[^}]*}/##p' "$tmp/docker-compose.yml"); do
    printf 'x' > "$tmp/secrets/local/$f"
  done
  [[ "$omit" == "omit-portainer" ]] && rm -f "$tmp/secrets/local/portainer_admin_password.txt"
  printf '%s\n' "$line" > "$tmp/.env"
  bash "$tmp/scripts/check-secret-files.sh" >/dev/null 2>&1; rc=$?
  rm -rf "$tmp"
  if [[ "$rc" == "$expected" ]]; then
    printf 'ok   LAB_SECRETS_DIR %s (exit %s)\n' "$name" "$rc"
  else
    printf 'FAIL LAB_SECRETS_DIR %s: expected exit %s, got %s\n' "$name" "$expected" "$rc"
    (( FAILS++ )) || true
  fi
}

# Every file present: each .env form must resolve to ./secrets/local (exit 0).
run_env_fixture "plain" 0 'LAB_SECRETS_DIR=./secrets/local'
run_env_fixture "double-quoted" 0 'LAB_SECRETS_DIR="./secrets/local"'
run_env_fixture "single-quoted" 0 "LAB_SECRETS_DIR='./secrets/local'"
run_env_fixture "trailing comment" 0 'LAB_SECRETS_DIR=./secrets/local # generated by make secrets'
run_env_fixture "quoted with comment" 0 'LAB_SECRETS_DIR="./secrets/local"  # generated'

# portainer_admin_password.txt missing: each form must be checked and fail (exit 1).
run_env_fixture "plain, missing file" 1 'LAB_SECRETS_DIR=./secrets/local' omit-portainer
run_env_fixture "double-quoted, missing file" 1 'LAB_SECRETS_DIR="./secrets/local"' omit-portainer
run_env_fixture "single-quoted, missing file" 1 "LAB_SECRETS_DIR='./secrets/local'" omit-portainer
run_env_fixture "trailing comment, missing file" 1 'LAB_SECRETS_DIR=./secrets/local # generated by make secrets' omit-portainer
run_env_fixture "quoted with comment, missing file" 1 'LAB_SECRETS_DIR="./secrets/local"  # generated' omit-portainer

# Required credentials: no fallback, generated by make secrets.
bash "$HERE/test-admin-credentials.sh" || (( FAILS++ )) || true

# Backup/restore failure paths. Cases that need PostgreSQL server binaries
# skip cleanly when they are not installed.
bash "$HERE/test-backup-restore.sh" || (( FAILS++ )) || true

(( FAILS == 0 )) || exit 1
